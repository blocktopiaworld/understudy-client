// Generates a protocol/versions/version_<v>_components.go table from a server's
// own registries report.
//
// Usage: node gencomponents.mjs <registries.json> <version> <out.go>
//   e.g. node gencomponents.mjs /tmp/reports/registries.json 26.1 \
//          ../../protocol/versions/version_26_1_components.go
//
// Get the report by running the server jar with the data generator:
//
//   java -DbundlerMainClass=net.minecraft.data.Main -jar server.jar --reports
//
// # Why this is not generated from minecraft-data
//
// Because minecraft-data does not carry it. There is no published list of data
// component types anywhere, and the ids are dense registry indices that shift
// whenever Mojang inserts one. Between 1.21.4 and 26.1 only five of sixty-seven
// kept their number.
//
// # What the table is
//
// A map from this version's wire id to the canonical id the decoder switches
// on, which is 26.1's numbering — arbitrary, except that 26.1 is the version
// every payload shape in understudy/components.go was read off. Matching is by
// name, so a component that moved is followed and one that does not exist under
// that name in the canonical set is left out rather than guessed at.
//
// The generator is deliberately loud, like genversion.mjs. A component present
// here and absent from the canonical set is reported by name, because the
// alternative is a decoder that silently treats an unknown id as some other
// component and desynchronises the rest of the packet.
import fs from 'node:fs'

const [, , reportPath, version, outPath] = process.argv
if (!reportPath || !version || !outPath) {
  console.error('usage: gencomponents.mjs <registries.json> <version> <out.go>')
  process.exit(1)
}

const REGISTRY = 'minecraft:data_component_type'

function table(path) {
  const registries = JSON.parse(fs.readFileSync(path, 'utf8'))
  const registry = registries[REGISTRY]
  if (!registry) throw new Error(`${path} has no ${REGISTRY}`)
  const byName = new Map()
  for (const [name, entry] of Object.entries(registry.entries)) {
    byName.set(name.replace(/^minecraft:/, ''), entry.protocol_id)
  }
  return byName
}

// The canonical numbering. Kept beside the generator rather than read from a
// report so that generating a table does not depend on having 26.1's report to
// hand as well — and so a change to it is a visible edit.
const canonicalPath = new URL('./canonical-components.json', import.meta.url)
const canonical = new Map(Object.entries(JSON.parse(fs.readFileSync(canonicalPath, 'utf8'))))

const mine = table(reportPath)
const rows = []
const unknown = []
for (const [name, id] of [...mine].sort((a, b) => a[1] - b[1])) {
  if (canonical.has(name)) rows.push([id, canonical.get(name), name])
  else unknown.push(`${name} (${id})`)
}

if (unknown.length) {
  console.error(
    `${version}: ${unknown.length} component(s) have no canonical id and are ` +
      `left out of the table, so an item carrying one will stop the scan:\n  ` +
      unknown.join('\n  '),
  )
}

const ident = version.replace(/\./g, '_')
const width = Math.max(...rows.map(([id]) => String(id).length))
const body = rows
  .map(([id, want, name]) => `\t${String(id).padStart(width)}: ${want}, // ${name}`)
  .join('\n')

fs.writeFileSync(
  outPath,
  `package versions

// Data component type ids for Minecraft ${version}.
//
// Code generated by internal/gen/gencomponents.mjs from the server's own
// registries report. DO NOT EDIT.
//
// Keys are this version's wire ids; values are the canonical ids that
// understudy/components.go switches on, which is 26.1's numbering. An id absent
// from this map is a component this decoder has no shape for.
var v${ident}ComponentIDs = map[int32]int32{
${body}
}
`,
)

console.error(`${version}: ${rows.length} component id(s) written to ${outPath}`)
